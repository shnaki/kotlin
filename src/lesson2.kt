fun main() {
    /**
     * ・画面出力。
     * ・四則演算。
     * ・文字列結合。
     */

    // 画面出力。
    println(100)
    println("Hello")

    print("Hello\nWorld")

    // 算術演算子 +, -, *, /, %
    println(10 + 2)
    println(10 - 2)
    println(10 * 2)
    println(10 / 2)
    println(10 % 2)

    // 文字列結合
    println("Hello" + "World")
}
